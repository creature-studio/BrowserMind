#!/usr/bin/env node
/**
 * Generates the extension's plugin index.
 *
 * Plugin folders are the single source of truth: this script turns
 * `plugins/<id>/plugin.json` (+ optional adapter module) into
 *
 *   packages/extension/src/generated/plugin-manifests.ts  ← pure data, used for
 *       host permissions and for the runtime-installed plugin catalog
 *   packages/extension/src/generated/plugin-modules.ts    ← bundled imports so
 *       the content script can instantiate every built-in plugin
 *
 * Run automatically on `npm install` (postinstall) and in CI; run by hand after
 * adding a provider: `npm run plugins:sync`.
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pluginsDir = path.join(root, 'plugins');
const outDir = path.join(root, 'packages', 'extension', 'src', 'generated');

const ADAPTER_CANDIDATES = ['adapter.ts', 'adapter.js', 'index.ts', 'index.js'];

function identifierFor(id) {
  return id.replace(/[^a-zA-Z0-9]+(.)/g, (_, char) => char.toUpperCase()).replace(/^[0-9]/, '_$&');
}

async function main() {
  const entries = await readdir(pluginsDir, { withFileTypes: true });
  const plugins = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const dir = path.join(pluginsDir, entry.name);
    const manifestPath = path.join(dir, 'plugin.json');
    if (!existsSync(manifestPath)) continue;
    const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
    const adapter = ADAPTER_CANDIDATES.map((candidate) => path.join(dir, candidate)).find((file) => existsSync(file));
    plugins.push({ manifest, dirName: entry.name, adapter });
  }
  plugins.sort((a, b) => a.manifest.id.localeCompare(b.manifest.id));

  const relative = (target) =>
    path.relative(outDir, target).replace(/\\/g, '/').replace(/\.ts$/, '').replace(/\.js$/, '');

  const manifestsFile = `/**
 * AUTO-GENERATED by scripts/generate-plugin-index.mjs — do not edit by hand.
 * Run \`npm run plugins:sync\` after adding or changing a plugin folder.
 *
 * Pure data: no imports, safe to consume from the build config.
 */
import type { PluginManifest } from '@browsermind/core/browser';

export const PLUGIN_MANIFESTS: PluginManifest[] = ${JSON.stringify(
    plugins.map((plugin) => plugin.manifest),
    null,
    2,
  )};

/** Every match pattern of every plugin folder — becomes manifest host_permissions. */
export const PLUGIN_MATCH_PATTERNS: string[] = ${JSON.stringify(
    [...new Set(plugins.flatMap((plugin) => plugin.manifest.matchPatterns ?? []))].sort(),
    null,
    2,
  )};

/** Plugin ids in the order they were discovered. */
export const PLUGIN_IDS: string[] = ${JSON.stringify(plugins.map((plugin) => plugin.manifest.id), null, 2)};

export const PLUGIN_COUNT = ${plugins.length};
`;

  const importLines = [];
  const factoryLines = [];
  for (const plugin of plugins) {
    const varName = `${identifierFor(plugin.manifest.id)}Import`;
    if (plugin.adapter) {
      importLines.push(`import ${varName} from '${relative(plugin.adapter)}';`);
      factoryLines.push(
        `  resolve('${plugin.manifest.id}', ${varName} as BrowserAIPlugin | { default?: BrowserAIPlugin } | undefined),`,
      );
    } else {
      importLines.push(`import ${varName} from '${relative(path.join(pluginsDir, plugin.dirName, 'plugin.json'))}';`);
      factoryLines.push(`  createDeclarativePlugin(${varName} as unknown as PluginManifest),`);
    }
  }

  const modulesFile = `/**
 * AUTO-GENERATED by scripts/generate-plugin-index.mjs — do not edit by hand.
 *
 * Static imports (instead of a runtime directory scan) so the bundler can tree
 * shake, and so a missing plugin is a build error rather than a blank page.
 * Adding a provider = adding a folder + running \`npm run plugins:sync\`.
 */
import { createDeclarativePlugin, type BrowserAIPlugin, type PluginManifest } from '@browsermind/core/browser';
${importLines.join('\n')}

function resolve(id: string, module: BrowserAIPlugin | { default?: BrowserAIPlugin } | undefined): BrowserAIPlugin {
  const plugin = (module as { default?: BrowserAIPlugin })?.default ?? (module as BrowserAIPlugin);
  if (!plugin || typeof plugin.createAdapter !== 'function') {
    throw new Error(\`Plugin module "\${id}" does not export a BrowserAIPlugin\`);
  }
  return plugin;
}

/** Every plugin bundled into the extension. */
export function builtinPlugins(): BrowserAIPlugin[] {
  return [
${factoryLines.join('\n')}
  ];
}
`;

  await mkdir(outDir, { recursive: true });
  await writeFile(path.join(outDir, 'plugin-manifests.ts'), manifestsFile, 'utf8');
  await writeFile(path.join(outDir, 'plugin-modules.ts'), modulesFile, 'utf8');
  console.log(`[plugins:sync] ${plugins.length} plugins → packages/extension/src/generated/`);
  for (const plugin of plugins) {
    console.log(`  ${plugin.manifest.id.padEnd(12)} ${plugin.adapter ? 'code   ' : 'declarative'} ${plugin.manifest.matchPatterns.join(', ')}`);
  }
}

main().catch((error) => {
  console.error('[plugins:sync] failed:', error);
  process.exit(1);
});
